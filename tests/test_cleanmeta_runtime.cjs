const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const window = {PRISM_APP_PARTS: []};
vm.runInNewContext(fs.readFileSync('prism/vendor/app-24-cleanmeta.js', 'utf8'), {window, Blob, URL, setTimeout});
(async () => {
  const app = window.PRISM_APP_PARTS[0]();
  const requests = [];
  const defaults = {ok: true, prompts: {screen: '선별 기본', detail: '상세 기본'}, external_facts: [{id: 'verified.minor'}, {id: 'verified.false'}]};
  app._authHeaders = () => ({Authorization: 'Bearer test'});
  app._afetch = async (url, init) => {
    requests.push({url, init});
    return {ok: true, json: async () => JSON.parse(init.body).action === 'defaults' ? defaults : {ok: true, mock: true, runs: []}};
  };
  app.cmTitle = '제목'; app.cmBody = '<script>원문</script>'; app.cmContext = '확인 자료';
  await app.cmTry();
  assert.equal(requests.length, 2);
  assert.equal(requests[0].url, '/lab-cleanmeta-try');
  assert.deepEqual(JSON.parse(requests[0].init.body), {action: 'defaults'});
  assert.equal(requests[1].init.headers.Authorization, 'Bearer test');
  assert.deepEqual(JSON.parse(requests[1].init.body), {title: '제목', body: app.cmBody, context: '확인 자료', model: 'solar-decide', mode: 'cascade', gate: 0.9, input_price: null, policy_set: 'common_v1', prompts: defaults.prompts, requested_parts: ['body'], case_ref: '', reviewed_facts: []});
  assert.equal(app.cmBusy, false); assert.equal(app.cmResult.mock, true);
  app.cmScreenPrompt = '사용자 선별'; app.cmDetailPrompt = '사용자 상세';
  app.cmParts = ['image']; app.cmCaseRef = 'case-1'; app.cmAddFact(); app.cmAddFact(); app.cmAddFact();
  assert.equal(app.cmFacts.length, 2);
  app.cmFacts[0].value = 'present'; app.cmFacts[0].source = '확인 기록';
  app.cmModel = 'text-model'; await app.cmTry();
  const submitted = JSON.parse(requests[2].init.body);
  assert.equal(submitted.model, 'text-model'); assert.equal(submitted.prompts.detail, '사용자 상세');
  assert.equal(submitted.reviewed_facts[0].subject_ref, 'case-1'); assert.deepEqual(submitted.requested_parts, ['body', 'image']);
  app.cmResetPrompt('screen'); assert.equal(app.cmScreenPrompt, '선별 기본'); assert.equal(app.cmDetailPrompt, '사용자 상세');
  app.cmResetPrompt('detail'); assert.equal(app.cmDetailPrompt, '상세 기본');
  app.cfg = {forcedMock: false};
  app.textGroups = [{on: true, items: [{model: 'text-model'}, {model: 'text-model'}]}, {on: false, items: [{model: 'offline-model'}]}];
  assert.equal(app.cmModels.filter(x => x === 'text-model').length, 1); assert.equal(app.cmModels.includes('offline-model'), false);
  app.cmPolicySet = 'vl13'; await app.cmTry();
  assert.equal('prompts' in JSON.parse(requests[3].init.body), false);
  app.cmBusy = true; await app.cmTry(); assert.equal(requests.length, 4); app.cmBusy = false;
  app._afetch = async () => ({ok: false, json: async () => ({error: '권한 없음'})});
  await app.cmTry(); assert.equal(app.cmResult, null); assert.equal(app.cmError, '권한 없음'); assert.equal(app.cmBusy, false);
  app.cmDefaults = null; app.cmPolicySet = 'common_v1';
  app._afetch = async () => ({ok: true, json: async () => ({ok: true})});
  await app.cmTry(); assert.equal(app.cmDefaults, null); assert.equal(app.cmResult, null); assert.match(app.cmError, /기본 프롬프트/);
  app._afetch = async () => {throw new Error('연결 실패');};
  await app.cmTry(); assert.equal(app.cmError, '연결 실패'); assert.equal(app.cmBusy, false); assert.equal(app.cmLoadingDefaults, false);
  assert.equal(app.cmProbability(null), '미제공'); assert.equal(app.cmProbability(0), '0.0%');
  assert.equal(app.cmScoreLabel({score_source: 'llm_self_report'}), '판단 점수 (모델 자기보고)');
  console.log('cleanmeta frontend runtime: passed');
})().catch(e => {console.error(e); process.exitCode = 1;});

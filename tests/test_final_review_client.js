const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const window = {};
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../prism/vendor/app-20-operations.js'), 'utf8'), {window});
const app = window.PRISM_APP_PARTS[0]();
(async () => {
  const hash='1234567890abcdef';
  app.finalMode=true;app.finalCtx={hash,final_reason:'의견 갈림'};app.detail={hash};
  const axes=Object.fromEntries(app.opsFields.map(f=>[f.key,{status:'accurate'}]));
  const response={hash,basis:{token:'t'},revision:1,cases:[],review:{axes},final_review:null};
  app.opsRequest=async()=>response;
  await app.opsOpen({hash});
  assert.equal(app.opsAxes.summary.status,'','초기 판정을 최종 판정에 미리 선택하지 않는다');
  response.final_review={axes};
  await app.opsOpen({hash});
  assert.equal(app.opsAxes.summary.status,'accurate');
  let sent;
  app.opsSave=async data=>{sent=data;return response;};app.loadRaw=async()=>{};
  await app.opsSaveReview();
  assert.equal(sent.action,'final_review');
  app.finalMode=false;
  await app.opsSaveReview();
  assert.equal(sent.action,'review');
  let shown=false;
  app.$refs={finalHistoryDialog:{showModal(){shown=true;}}};
  app.opsRequest=async()=>{throw Error('연결 실패');};
  await app.openFinalHistory({hash,fb:{verdicts:[]}});
  assert.equal(shown,true);
  assert.equal(app.finalHistoryBusy,false);
  assert.equal(app.finalHistoryError,'연결 실패');
  console.log('final review client: OK');
})().catch(e=>{console.error(e);process.exitCode=1;});
